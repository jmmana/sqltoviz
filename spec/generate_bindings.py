#!/usr/bin/env python3
"""Generate per-language contract constants from the frozen spec (single source of truth).

Usage: python spec/generate_bindings.py          # (re)write generated files
       python spec/generate_bindings.py --check  # exit 1 if any generated file is stale (used by CI)
Verifies the SHA256 of spec/sqlvizspec-v1-features.json against the pinned value before generating.
Generated: packages/python/sqltoviz/_contract.py, packages/npm/src/contract.ts, packages/nuget/SqlToViz/Contract.cs
"""
import hashlib, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "sqlvizspec-v1-features.json"
PINNED_SHA256 = "d14d140b9118c0b535d4e504af7f16546f47d56ac8f1692c2ab62615686e5864"
raw = SPEC.read_bytes()
sha = hashlib.sha256(raw).hexdigest()
if sha != PINNED_SHA256:
    sys.exit(f"spec bytes do not match the pinned contract hash ({sha})")
c = json.loads(raw)
groups = {k: [(f["name"], f["range"][0], f["range"][1], f["default"]) for f in c[k]] for k in ("sql_features", "global_features", "column_features")}
classes, roles = c["model_io"]["base_classes"], c["model_io"]["roles"]
types = c["canonical"]["types"]
assert [len(groups[k]) for k in groups] == [16, 16, 28]


def num(x):
    return repr(float(x)) if not float(x).is_integer() else str(int(x))


def py():
    out = ['"""GENERATED by spec/generate_bindings.py from spec/sqlvizspec-v1-features.json - do not edit."""',
           f'CONTRACT_VERSION = {c["contract_version"]!r}', f'CONTRACT_SHA256 = {sha!r}', f'MAX_COLUMNS = {c["max_columns"]}', f'MAX_ROWS = {c["max_rows"]}',
           f"BASE_CLASSES = {tuple(classes)!r}", f"ROLES = {tuple(roles)!r}", f"TYPES = {tuple(types)!r}"]
    for k, v in groups.items():
        out.append(f"{k.upper()} = (")
        out += [f"    ({n!r}, {num(lo)}, {num(hi)}, {num(d)})," for n, lo, hi, d in v]
        out.append(")")
    return "\n".join(out) + "\n"


def ts():
    out = ["// GENERATED by spec/generate_bindings.py from spec/sqlvizspec-v1-features.json - do not edit.",
           f'export const CONTRACT_VERSION = {json.dumps(c["contract_version"])};', f'export const CONTRACT_SHA256 = {json.dumps(sha)};',
           f'export const MAX_COLUMNS = {c["max_columns"]};', f'export const MAX_ROWS = {c["max_rows"]};',
           f"export const BASE_CLASSES = {json.dumps(classes)} as const;", f"export const ROLES = {json.dumps(roles)} as const;",
           f"export const TYPES = {json.dumps(types)} as const;", "export type FeatureDef = readonly [name: string, lo: number, hi: number, dflt: number];"]
    for k, v in groups.items():
        out.append(f"export const {k.upper()}: readonly FeatureDef[] = [")
        out += [f"  [{json.dumps(n)}, {num(lo)}, {num(hi)}, {num(d)}]," for n, lo, hi, d in v]
        out.append("];")
    return "\n".join(out) + "\n"


def cs():
    def arr(name, v):
        items = ",\n    ".join(f'("{n}", {num(lo)}d, {num(hi)}d, {num(d)}d)' for n, lo, hi, d in v)
        return f"  public static readonly (string Name, double Lo, double Hi, double Default)[] {name} = {{\n    {items}\n  }};"
    return ("// <auto-generated> by spec/generate_bindings.py from spec/sqlvizspec-v1-features.json - do not edit. </auto-generated>\n"
            "namespace SqlToViz;\npublic static class Contract {\n"
            f'  public const string Version = "{c["contract_version"]}";\n  public const string Sha256 = "{sha}";\n'
            f'  public const int MaxColumns = {c["max_columns"]};\n  public const int MaxRows = {c["max_rows"]};\n'
            f'  public static readonly string[] BaseClasses = {{ {", ".join(json.dumps(x) for x in classes)} }};\n'
            f'  public static readonly string[] Roles = {{ {", ".join(json.dumps(x) for x in roles)} }};\n'
            f'  public static readonly string[] Types = {{ {", ".join(json.dumps(x) for x in types)} }};\n'
            + arr("SqlFeatures", groups["sql_features"]) + "\n" + arr("GlobalFeatures", groups["global_features"]) + "\n"
            + arr("ColumnFeatures", groups["column_features"]) + "\n}\n")


targets = {ROOT / "packages/python/sqltoviz/_contract.py": py(), ROOT / "packages/npm/src/contract.ts": ts(), ROOT / "packages/nuget/SqlToViz/Contract.cs": cs()}
bad = []
for p, text in targets.items():
    if "--check" in sys.argv:
        if not p.exists() or p.read_text() != text:
            bad.append(str(p.relative_to(ROOT)))
    else:
        p.write_text(text)
if bad:
    sys.exit("stale generated files: " + ", ".join(bad))
print("ok:", ", ".join(str(p.relative_to(ROOT)) for p in targets))
