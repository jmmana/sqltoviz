#!/usr/bin/env python3
"""Generate per-language contract constants from the frozen spec (single source of truth).

Usage: python spec/generate_bindings.py          # (re)write generated files
       python spec/generate_bindings.py --check  # exit 1 if any generated file is stale (used by CI)
Verifies the SHA256 of spec/sqlvizspec-v1-features.json against the pinned value before generating.
Generated: packages/python/sqltoviz/_contract.py, packages/npm/src/contract.ts, packages/nuget/SqlToViz/Contract.cs
Second target (additive outputs contract): _outputs.py, outputs-contract.ts, OutputsContract.cs from spec/sqlvizspec-v1-outputs.json (pinned separately,
bound to the base hash via base_contract_sha256).
"""
import hashlib, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "sqlvizspec-v1-features.json"
PINNED_SHA256 = "d14d140b9118c0b535d4e504af7f16546f47d56ac8f1692c2ab62615686e5864"
raw = SPEC.read_bytes()
sha = hashlib.sha256(raw).hexdigest()
if sha != PINNED_SHA256:
    sys.exit(f"spec bytes do not match the pinned contract hash ({sha})")
c = json.loads(raw)
groups = {k: [(f["name"], f["range"][0], f["range"][1], f["default"]) for f in c[k]] for k in ("sql_features", "global_features", "column_features")}
classes, roles = c["model_io"]["base_classes"], c["model_io"]["roles"]
types = c["canonical"]["types"]
assert [len(groups[k]) for k in groups] == [16, 16, 28]


def num(x):
    return repr(float(x)) if not float(x).is_integer() else str(int(x))


def py():
    out = ['"""GENERATED by spec/generate_bindings.py from spec/sqlvizspec-v1-features.json - do not edit."""',
           f'CONTRACT_VERSION = {c["contract_version"]!r}', f'CONTRACT_SHA256 = {sha!r}', f'MAX_COLUMNS = {c["max_columns"]}', f'MAX_ROWS = {c["max_rows"]}',
           f"BASE_CLASSES = {tuple(classes)!r}", f"ROLES = {tuple(roles)!r}", f"TYPES = {tuple(types)!r}"]
    for k, v in groups.items():
        out.append(f"{k.upper()} = (")
        out += [f"    ({n!r}, {num(lo)}, {num(hi)}, {num(d)})," for n, lo, hi, d in v]
        out.append(")")
    return "\n".join(out) + "\n"


def ts():
    out = ["// GENERATED by spec/generate_bindings.py from spec/sqlvizspec-v1-features.json - do not edit.",
           f'export const CONTRACT_VERSION = {json.dumps(c["contract_version"])};', f'export const CONTRACT_SHA256 = {json.dumps(sha)};',
           f'export const MAX_COLUMNS = {c["max_columns"]};', f'export const MAX_ROWS = {c["max_rows"]};',
           f"export const BASE_CLASSES = {json.dumps(classes)} as const;", f"export const ROLES = {json.dumps(roles)} as const;",
           f"export const TYPES = {json.dumps(types)} as const;", "export type FeatureDef = readonly [name: string, lo: number, hi: number, dflt: number];"]
    for k, v in groups.items():
        out.append(f"export const {k.upper()}: readonly FeatureDef[] = [")
        out += [f"  [{json.dumps(n)}, {num(lo)}, {num(hi)}, {num(d)}]," for n, lo, hi, d in v]
        out.append("];")
    return "\n".join(out) + "\n"


def cs():
    def arr(name, v):
        items = ",\n    ".join(f'("{n}", {num(lo)}d, {num(hi)}d, {num(d)}d)' for n, lo, hi, d in v)
        return f"  public static readonly (string Name, double Lo, double Hi, double Default)[] {name} = {{\n    {items}\n  }};"
    return ("// <auto-generated> by spec/generate_bindings.py from spec/sqlvizspec-v1-features.json - do not edit. </auto-generated>\n"
            "namespace SqlToViz;\npublic static class Contract {\n"
            f'  public const string Version = "{c["contract_version"]}";\n  public const string Sha256 = "{sha}";\n'
            f'  public const int MaxColumns = {c["max_columns"]};\n  public const int MaxRows = {c["max_rows"]};\n'
            f'  public static readonly string[] BaseClasses = {{ {", ".join(json.dumps(x) for x in classes)} }};\n'
            f'  public static readonly string[] Roles = {{ {", ".join(json.dumps(x) for x in roles)} }};\n'
            f'  public static readonly string[] Types = {{ {", ".join(json.dumps(x) for x in types)} }};\n'
            + arr("SqlFeatures", groups["sql_features"]) + "\n" + arr("GlobalFeatures", groups["global_features"]) + "\n"
            + arr("ColumnFeatures", groups["column_features"]) + "\n}\n")


targets = {ROOT / "packages/python/sqltoviz/_contract.py": py(), ROOT / "packages/npm/src/contract.ts": ts(), ROOT / "packages/nuget/SqlToViz/Contract.cs": cs()}

# ---- second target: additive outputs contract (spec/sqlvizspec-v1-outputs.json); the base files above are unaffected
OUT_SPEC = ROOT / "spec" / "sqlvizspec-v1-outputs.json"
OUT_PINNED_SHA256 = "45581c7b4414fc6250fb57988e04811bc4492fb1bbc21841058589481cce01db"
oraw = OUT_SPEC.read_bytes()
osha = hashlib.sha256(oraw).hexdigest()
if osha != OUT_PINNED_SHA256:
    sys.exit(f"outputs spec bytes do not match the pinned hash ({osha})")
oc = json.loads(oraw)
if oc["base_contract_sha256"] != PINNED_SHA256:
    sys.exit("outputs spec is bound to a different base contract")
_compact = json.dumps(oc, ensure_ascii=False, separators=(",", ":"))


def out_py():
    return ('"""GENERATED by spec/generate_bindings.py from spec/sqlvizspec-v1-outputs.json - do not edit."""\n'
            f'OUTPUTS_VERSION = {oc["contract_version"]!r}\nOUTPUTS_SHA256 = {osha!r}\nBASE_CONTRACT_SHA256 = {oc["base_contract_sha256"]!r}\n'
            f'OUTPUTS = {tuple(oc["outputs"])!r}\nALIASES = {oc["aliases"]!r}\nSPECIALIZATION = {oc["specialization"]!r}\n'
            f'THRESHOLDS = {oc["thresholds"]!r}\nTOLERANCE = {oc["tolerance"]!r}\nREASON_CODES = {tuple(oc["reason_codes"])!r}\n'
            f'DEFINITIONS = {oc["outputs_definition"]!r}\n')


def out_ts():
    return ("// GENERATED by spec/generate_bindings.py from spec/sqlvizspec-v1-outputs.json - do not edit.\n"
            f'export const OUTPUTS_VERSION = {json.dumps(oc["contract_version"])};\nexport const OUTPUTS_SHA256 = {json.dumps(osha)};\n'
            f'export const BASE_CONTRACT_SHA256 = {json.dumps(oc["base_contract_sha256"])};\n'
            f'export const OUTPUTS = {json.dumps(oc["outputs"])} as const;\nexport const ALIASES: Readonly<Record<string, string>> = {json.dumps(oc["aliases"])};\n'
            f'export const SPECIALIZATION: Readonly<Record<string, readonly string[]>> = {json.dumps(oc["specialization"], ensure_ascii=False)};\n'
            f'export const THRESHOLDS = {json.dumps(oc["thresholds"], ensure_ascii=False)} as const;\nexport const TOLERANCE = {json.dumps(oc["tolerance"])} as const;\n'
            "export interface OutputPrecondition { readonly id: string; readonly reason: string }\n"
            "export interface OutputDefinition { readonly requires_base_eligibility: boolean; readonly channels: readonly string[]; readonly preconditions: readonly OutputPrecondition[] }\n"
            f'export const REASON_CODES = {json.dumps(oc["reason_codes"])} as const;\n'
            f'export const DEFINITIONS: Readonly<Record<string, OutputDefinition>> = {json.dumps(oc["outputs_definition"], ensure_ascii=False)};\n')


def out_cs():
    assert '"""' not in _compact
    return ("// <auto-generated> by spec/generate_bindings.py from spec/sqlvizspec-v1-outputs.json - do not edit. </auto-generated>\n"
            "namespace SqlToViz;\npublic static class OutputsContract {\n"
            f'  public const string Version = "{oc["contract_version"]}";\n  public const string Sha256 = "{osha}";\n  public const string BaseContractSha256 = "{oc["base_contract_sha256"]}";\n'
            f'  public static readonly string[] Outputs = {{ {", ".join(json.dumps(x) for x in oc["outputs"])} }};\n'
            f'  public static readonly string[] ReasonCodes = {{ {", ".join(json.dumps(x) for x in oc["reason_codes"])} }};\n'
            "  // Full specification (specialization map, thresholds, tolerance, per-output preconditions and channels) as compact JSON; parse once at startup.\n"
            f'  public const string Json = """{_compact}""";\n}}\n')


targets.update({ROOT / "packages/python/sqltoviz/_outputs.py": out_py(), ROOT / "packages/npm/src/outputs-contract.ts": out_ts(),
                ROOT / "packages/nuget/SqlToViz/OutputsContract.cs": out_cs()})
bad = []
for p, text in targets.items():
    if "--check" in sys.argv:
        if not p.exists() or p.read_text() != text:
            bad.append(str(p.relative_to(ROOT)))
    else:
        p.write_text(text)
if bad:
    sys.exit("stale generated files: " + ", ".join(bad))
print("ok:", ", ".join(str(p.relative_to(ROOT)) for p in targets))
